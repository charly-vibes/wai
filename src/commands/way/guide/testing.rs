//! Topic guides for `wai way <topic>`.

use std::path::Path;

const TESTING_GUIDE: &str = r#"> *Facilitation guide generated by `wai way testing` — instructs an LLM to lead an interactive discussion with the user.*

# Testing Guide

**TL;DR**: Walk through 5 topics to build the test stack: example tests,
property-based testing, UI property testing, formal verification, and the
exec harness. For each: explain trade-offs, ask the user's preference,
recommend tooling. Current state: {current_state}.

You are helping the user set up the recommended testing stack for this
repository. Walk through the topics below **one at a time**, asking about
their goals and constraints before recommending tooling.

## Current State

- **Detected**: {current_state}

## Discussion Topics

### 1. Example-Based Baseline
Property tests and formal verification complement — never replace — plain
example tests. Cover known regressions as deterministic examples first;
properties generalize, examples pin specific bugs.
- **→ Ask:** Do they have a baseline example suite? Which runner (cargo test,
  vitest, pytest, go test)?

### 2. Property-Based Testing — Rust: Hegel (`https://hegel.dev/`)
Hegel (`https://hegel.dev/`) (crate `hegeltest`) is the recommended PBT engine
for Rust: harness-driven (`#[hegel::test]`, `#[hegel::state_machine]` +
`#[rule]`/`#[invariant]`), internal shrinking, a failing-example database
(`.hegel/examples`), and a derandomized `ci` profile.
- Start with pure predicates and state machines over the core domain types.
- Prefer constructor-driven generators over `assume` filters.
- Existing `proptest` suites stay until a file is deliberately ported —
  don't rewrite working properties wholesale.
- Add `hegeltest` as a dev-dependency only; never in shipped runtime paths.
- **→ Ask:** Which module has the weakest test coverage but the strongest
  invariants? Start there.

### 3. Property-Based Testing — UIs: Bombadil (`https://github.com/antithesishq/bombadil`)
Bombadil (`https://github.com/antithesishq/bombadil`) (Antithesis) does
property-based testing for web and terminal UIs — it autonomously explores
the UI and validates correctness properties, finding harder bugs earlier.
Runs locally, in CI, and inside Antithesis.
- Best fit: apps with meaningful UI invariants (nothing breaks, state stays
  consistent, flows always completable).
- **→ Ask:** Do they have UI flows whose invariants are checked manually
  today? Those are the first bombadil properties.

### 4. Formal Verification — Rust: Kani (`https://model-checking.github.io/kani/`)
Kani (`https://model-checking.github.io/kani/`) is the Rust model checker:
it proves properties over *all* executions (no sampling) — no panics, no
arithmetic overflow, no unreachable states, custom `#[kani::proof]`
invariants. Especially valuable for unsafe code and parsers/protocol code
where a property bug is a security bug.
- Cost: slow per-proof, so verify targeted functions and invariants, not
  whole crates.
- **→ Ask:** Is there unsafe code, an FFI boundary, or a parser worth
  proving? That's where Kani pays for itself.

### 5. Exec Harness
Once properties exist, wire them into the standard test loop so agents and
CI run the affected set instead of the full suite.
- **Rust/charly-vibes repos**: testaruda (`https://github.com/charly-vibes/testaruda`)
  — `just test` (select → run → ingest against the working diff),
  `just test-full` for the plain suite.
- **→ Ask:** Should property tests run in the fast loop, in CI only, or
  both? (Hegel's `ci` profile derandomizes; keep flaky-prone properties CI-only.)

## Guidelines

- If the user says they already have something or want to skip a topic, move on.
- If the user says "just pick for me": Hegel for Rust PBT, Bombadil for UIs,
  Kani only if unsafe/parsers exist, testaruda for the loop.
- One concern per property; keep properties cheap enough to run on save.
- Deterministic examples for found bugs — every property failure becomes a
  regression example (Hegel's failing-example DB does this automatically).
"#;

pub(crate) fn guide_testing(repo_root: &Path) -> String {
    let cargo = std::fs::read_to_string(repo_root.join("Cargo.toml")).unwrap_or_default();
    let has_hegel = cargo.contains("hegeltest");
    let has_proptest = cargo.contains("proptest");
    let has_kani = cargo.contains("kani") || repo_root.join(".kani").exists();

    let mut detected = Vec::new();
    if has_hegel {
        detected.push("hegeltest (Hegel)");
    }
    if has_proptest {
        detected.push("proptest");
    }
    if has_kani {
        detected.push("kani");
    }

    let current_state = if detected.is_empty() {
        "No property testing or formal verification tooling detected".to_string()
    } else {
        format!("Detected: {}", detected.join(", "))
    };

    TESTING_GUIDE.replace("{current_state}", &current_state)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn testing_guide_recommends_hegel_bombadil_kani() {
        let tmp = tempfile::TempDir::new().unwrap_or_else(|e| panic!("unwrap failed: {e}"));
        let guide = guide_testing(tmp.path());
        assert!(guide.contains("Hegel"));
        assert!(guide.contains("hegel.dev"));
        assert!(guide.contains("Bombadil"));
        assert!(guide.contains("antithesishq/bombadil"));
        assert!(guide.contains("Kani"));
        assert!(guide.contains("model-checking.github.io/kani"));
        assert!(guide.contains("No property testing or formal verification tooling detected"));
    }

    #[test]
    fn testing_guide_detects_existing_tooling() {
        let tmp = tempfile::TempDir::new().unwrap_or_else(|e| panic!("unwrap failed: {e}"));
        std::fs::write(
            tmp.path().join("Cargo.toml"),
            "[dev-dependencies]\nhegeltest = \"0.52\"\nproptest = \"1\"\n",
        )
        .unwrap_or_else(|e| panic!("unwrap failed: {e}"));
        let guide = guide_testing(tmp.path());
        assert!(guide.contains("Detected: hegeltest (Hegel), proptest"));
    }
}
